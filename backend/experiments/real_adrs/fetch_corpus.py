"""Build a corpus of REAL Architecture Decision Records from public GitHub repositories.

Why: every benchmark in this project is generated by the project team. Whether the wording the methods were tested on resembles
real ADRs is unknown. This script collects real ones so that question can be measured (see docs/REAL_ADRS.md).

Method (all choices are visible here, because they bias the sample):
  1. GitHub repository SEARCH by topic (architecture-decision-records, adr, ...), pages 1-3, most-starred first.
  2. Keep repositories (licence recorded as a flag; only permissively licensed ones are used for the excerpts shown in the annotation sheet), not archived, CREATED BEFORE `--created-before`
     (default 2023-01-01: before LLM-assisted writing, so the ADRs are overwhelmingly human-written; a first run without this filter
     returned mostly 2025-26 repositories about ADRs for AI coding agents, kept separately as datasets/real_adrs_agent_era), and whose
     name/description does not say template/tool/awesome/example/tutorial/course/book (we want a project's own decisions, not teaching
     material). A short curated list of well-known projects (`--extra`) is added; it bypasses the name and date filters.
  3. Blobless shallow `git clone`, list paths, select ADR files: markdown files inside a directory named adr/adrs/decisions/
     architecture-decisions/... (README, index, template excluded).
  4. Keep repositories with at least MIN_ADRS ADR files; take at most CAP_PER_REPO of them (seeded random choice), so a single large
     repository cannot dominate.
  5. Record repository, path, commit SHA, licence, stars and a SHA-256 of the text in manifest.json. The TEXTS are written to
     datasets/real_adrs/corpus/ which is git-ignored: this project publishes the manifest and the analysis, not other people's files.

Known biases: GitHub-topic-tagged repositories; most-starred first; English ADR text only matters downstream, not here;
projects that bother to tag ADRs are probably more disciplined than average.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import re
import shutil
import subprocess
import tempfile
import time
import urllib.parse
import urllib.request

TOPICS = ["architecture-decision-records", "adr", "architectural-decision-records", "decision-records", "architecture-decisions"]
PERMISSIVE = {"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "MPL-2.0", "Unlicense", "CC0-1.0", "CC-BY-4.0", "CC-BY-SA-4.0", "0BSD"}
EXCLUDE_NAME = re.compile(r"(awesome|template|tool|example|sample|demo|tutorial|course|workshop|book|cheat|generator|boilerplate|starter|"
                          r"learn|training|playground|kata|^adr[-_/]|[-_/]adr$|madr|log4brains|adr-tools|dotfiles)", re.I)
TOPICS_BROAD = ["software-architecture", "domain-driven-design", "clean-architecture", "hexagonal-architecture", "modular-monolith", "microservices"]
# a directory whose name is 'adr'/'adrs' or contains 'decision' (architecture-decision-record, Architecture-Decision-Log, decision_records ...)
ADR_DIR = re.compile(r"(^|/)(?:adrs?|[^/]*decision[^/]*|adr[-_ ]docs?)/", re.I)
# ... and a file that looks like one record: numbered, dated, or called adr-*, so that 'decision-trees/guide.md' is not swept in
ADR_FILE = re.compile(r"(^|/)(?:\d{1,4}[-_. ]|\d{4}-\d{2}-\d{2}|adr[-_ ]?\d|adr[-_ ]|[a-z]{2,6}[-_]\d{2,4}[-_])[^/]*\.md$", re.I)
EXCLUDE_FILE = re.compile(r"(^|/)(readme|index|template|_template|summary|toc|contributing)[^/]*$|\.template\.", re.I)
MIN_ADRS, CAP_PER_REPO, MAX_REPOS = 5, 25, 400


def http_json(url: str) -> dict:
    req = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json", "User-Agent": "adr-corpus-research"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def search_candidates(pages: int, pause: float, created_before: str | None, extra: list[str]) -> list[dict]:
    seen, out = set(), []
    for chunk in [extra[i:i + 4] for i in range(0, len(extra), 4)]:  # curated repositories, a few per query
        q = urllib.parse.urlencode({"q": " ".join(f"repo:{r}" for r in chunk), "per_page": 100})
        try:
            for it in http_json(f"https://api.github.com/search/repositories?{q}").get("items", []):
                if it["full_name"] not in seen:
                    it["curated"] = True; seen.add(it["full_name"]); out.append(it)
        except Exception as e:
            print(f"curated search failed: {e}")
        time.sleep(pause)
    for topic, min_stars in [(t, 0) for t in TOPICS] + [(t, 30) for t in TOPICS_BROAD]:
        for page in range(1, pages + 1):
            query = f"topic:{topic}" + (f" created:<{created_before}" if created_before else "") + (f" stars:>={min_stars}" if min_stars else "")
            q = urllib.parse.urlencode({"q": query, "sort": "stars", "order": "desc", "per_page": 100, "page": page})
            try:
                items = http_json(f"https://api.github.com/search/repositories?{q}").get("items", [])
            except Exception as e:  # rate limit or network: keep what we have
                print(f"search {topic} p{page} failed: {e}")
                time.sleep(pause * 2)
                continue
            for it in items:
                if it["full_name"] not in seen:
                    seen.add(it["full_name"]); out.append(it)
            time.sleep(pause)
    return out


TOOLISH = re.compile(r"(adr|decision[- ]record|madr|template|cli\b|plugin|generator|viewer|linter|mkdocs|vscode|extension)", re.I)


def acceptable(it: dict, created_before: str | None = None) -> tuple[bool, str]:
    if it.get("archived") or it.get("fork"):
        return False, "archived or fork"
    if created_before and not it.get("curated") and (it.get("created_at") or "9999")[:10] >= created_before:
        return False, f"created {it.get('created_at', '')[:10]}, not before {created_before}"
    text = f"{it['full_name']} {it.get('description') or ''}"
    if not it.get("curated") and EXCLUDE_NAME.search(text):
        return False, "template/tool/teaching material by name or description"
    return True, ""


def adr_paths(paths: list[str]) -> list[str]:
    return [p for p in paths if p.lower().endswith(".md") and ADR_DIR.search(p) and ADR_FILE.search(p) and not EXCLUDE_FILE.search(p)]


def run(cmd, cwd=None, timeout=120):
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout)


def collect(it: dict, out_dir: str, rng: random.Random) -> dict | None:
    name = it["full_name"]
    tmp = tempfile.mkdtemp(prefix="adrfetch_")
    try:
        r = run(["git", "clone", "-q", "--depth", "1", "--filter=blob:none", "--no-checkout", f"https://github.com/{name}.git", tmp], timeout=150)
        if r.returncode:
            return None
        sha = run(["git", "rev-parse", "HEAD"], cwd=tmp).stdout.strip()
        paths = run(["git", "ls-tree", "-r", "HEAD", "--name-only"], cwd=tmp).stdout.split("\n")
        found = adr_paths([p for p in paths if p])
        if len(found) < MIN_ADRS:
            return None
        chosen = sorted(rng.sample(found, min(CAP_PER_REPO, len(found))))
        r = run(["git", "checkout", "-q", "HEAD", "--", *chosen], cwd=tmp, timeout=180)
        if r.returncode:
            return None
        dest = os.path.join(out_dir, name.replace("/", "__"))
        os.makedirs(dest, exist_ok=True)
        files = []
        for p in chosen:
            src = os.path.join(tmp, p)
            if not os.path.isfile(src):
                continue
            raw = open(src, "rb").read()
            if len(raw) > 60_000 or b"\x00" in raw:
                continue
            text = raw.decode("utf-8", errors="replace")
            fname = re.sub(r"[^A-Za-z0-9._-]+", "_", p)
            open(os.path.join(dest, fname), "w", encoding="utf-8").write(text)
            files.append({"file": f"{name.replace('/', '__')}/{fname}", "path": p, "sha256": hashlib.sha256(raw).hexdigest(), "bytes": len(raw),
                          "url": f"https://github.com/{name}/blob/{sha}/{urllib.parse.quote(p)}"})
        if len(files) < MIN_ADRS:
            shutil.rmtree(dest, ignore_errors=True)
            return None
        lic = (it.get("license") or {}).get("spdx_id")
        return {"repo": name, "commit": sha, "license": lic, "license_ok": lic in PERMISSIVE, "stars": it["stargazers_count"],
                "created": (it.get("created_at") or "")[:10], "curated": bool(it.get("curated")),
                "kind": "tool" if TOOLISH.search(f"{name} {it.get('description') or ''}") else "project",
                "description": it.get("description"), "adr_files_in_repo": len(found), "files": files}
    except subprocess.TimeoutExpired:
        return None
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="../datasets/real_adrs")
    ap.add_argument("--pages", type=int, default=3)
    ap.add_argument("--pause", type=float, default=7.0, help="seconds between search calls (unauthenticated limit: 10/min)")
    ap.add_argument("--seed", type=int, default=11)
    ap.add_argument("--max-repos", type=int, default=MAX_REPOS)
    ap.add_argument("--created-before", default="2023-01-01", help="ISO date; use '' to disable")
    ap.add_argument("--extra", default="", help="file with one owner/repo per line (curated well-known projects)")
    args = ap.parse_args(argv)
    os.makedirs(args.out, exist_ok=True)
    cand_path = os.path.join(args.out, "candidates.json")
    if os.path.exists(cand_path):
        cands = json.load(open(cand_path))
    else:
        extra = [l.strip() for l in open(args.extra) if l.strip() and not l.startswith("#")] if args.extra else []
        cands = search_candidates(args.pages, args.pause, args.created_before or None, extra)
        json.dump(cands, open(cand_path, "w"))
    print(f"{len(cands)} candidate repositories from topic search")
    rng, kept, skipped = random.Random(args.seed), [], {}
    corpus = os.path.join(args.out, "corpus")
    tried = 0
    for it in cands:
        ok, why = acceptable(it, args.created_before or None)
        if not ok:
            skipped[it["full_name"]] = why
            continue
        if tried >= args.max_repos:
            break
        tried += 1
        got = collect(it, corpus, rng)
        if got:
            kept.append(got); print(f"  kept {it['full_name']}: {len(got['files'])} of {got['adr_files_in_repo']} ADR files", flush=True)
            if len(kept) % 5 == 0:
                json.dump({"repos": kept, "partial": True}, open(os.path.join(args.out, "manifest.json"), "w"), indent=1)
        else:
            skipped[it["full_name"]] = f"fewer than {MIN_ADRS} ADR files, clone failed, or unreadable"
    manifest = {"method": __doc__.strip().split("\n\n")[1], "search_topics": TOPICS, "created_before": args.created_before, "seed": args.seed, "candidates": len(cands),
                "repos_tried": tried, "repos_kept": len(kept), "adrs": sum(len(k["files"]) for k in kept), "repos": kept,
                "skipped": {k: v for k, v in skipped.items()}}
    json.dump(manifest, open(os.path.join(args.out, "manifest.json"), "w"), indent=1)
    print(f"kept {len(kept)} repositories, {manifest['adrs']} ADRs -> {args.out}/manifest.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
